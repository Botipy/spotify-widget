const { contextBridge, ipcRenderer } = require('electron');

const call = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('sp', {
  authStatus: call('auth:status'),
  login: call('auth:login'),
  logout: call('auth:logout'),
  onLoggedOut: (cb) => ipcRenderer.on('auth:loggedOut', cb),
  onUpdate: (cb) => ipcRenderer.on('update:status', (_e, msg) => cb(msg)),
  libContains: call('library:contains'),
  libSet: call('library:set'),
  relogin: call('auth:relogin'),
  state: call('player:state'),
  toggle: call('player:toggle'),
  next: call('player:next'),
  prev: call('player:prev'),
  shuffle: call('player:shuffle'),
  seek: call('player:seek'),
  volume: call('player:volume'),
  playlists: call('playlists:get'),
  playPlaylist: call('playlists:play'),
  playlistTracks: call('playlists:tracks'),
  getSettings: call('settings:get'),
  setSettings: call('settings:set'),
  openSettings: call('settings:open'),
  appGet: call('app:get'),
  appSet: call('app:set'),
  appCheckUpdates: call('app:checkUpdates'),
  appInstallUpdate: call('app:installUpdate'),
  appLogout: call('app:logout'),
  pomoGet: call('pomo:get'),
  pomoCmd: call('pomo:cmd'),
  pomoSet: call('pomo:set'),
  pomoSuggest: call('pomo:suggest'),
  onPomo: (cb) => ipcRenderer.on('pomo:state', (_e, s) => cb(s)),
  onPomoSound: (cb) => ipcRenderer.on('pomo:sound', (_e, k) => cb(k)),
  onSettings: (cb) => ipcRenderer.on('settings:changed', (_e, s) => cb(s)),
  hide: call('win:hide'),
  quit: call('win:quit'),
  openUrl: call('win:openUrl'),
});
